def configure_data_worker_threads(worker_id: int) -> None:
    """Keep each spawned loader worker single-threaded.

    Formal launchers may run 48 workers per GPU task.  Without this guard,
    PyTorch/OpenMP-backed DSP can create another thread pool in every worker,
    causing severe oversubscription and long-tail stalls.
    """

    del worker_id
    for name in (
        "OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS",
        "NUMEXPR_NUM_THREADS", "VECLIB_MAXIMUM_THREADS",
    ):
        os.environ[name] = "1"
    torch.set_num_threads(1)
    try:
        torch.set_num_interop_threads(1)
    except RuntimeError:
        # PyTorch permits setting inter-op threads only before parallel work.
        # In that rare case the intra-op limit above remains the critical one.
        pass


def make_audio_loader(
    csv_path: str,
    cfg: Dict,
    *,
    train: bool,
    batch_size: int,
    num_workers: int,
    drop_last: bool | None = None,
) -> DataLoader:
    data = cfg["data"]
    branches = {
        name: value for name, value in cfg["audio_branches"].items() if value.get("enabled")
    }
    dataset = AudioSampleDataset(
        csv_path=csv_path,
        base_sample_rate=int(data["base_sample_rate"]),
        segment_seconds=float(data["segment_seconds"]),
        random_crop=bool(train and data.get("random_crop", True)),
        crop_mode=str(
            data.get(
                "crop_mode" if train else "eval_crop_mode",
                "random" if train else "center",
            )
        ),
        mono=bool(data.get("mono", False)),
        normalize=bool(data.get("normalize", True)),
        strict=bool(data.get("strict_audio", False)),
        auto_convert_mp3=bool(data.get("auto_convert_mp3", True)),
        audio_cache_dir=data.get("audio_cache_dir"),
        demucs_enabled=False,
    )
    collate = MultiBranchCollate(
        branch_cfg=branches,
        segment_seconds=float(data["segment_seconds"]),
        random_crop=bool(train and data.get("random_crop", True)),
        strict=bool(data.get("strict_audio", False)),
        crop_mode=str(
            data.get(
                "crop_mode" if train else "eval_crop_mode",
                "random" if train else "center",
            )
        ),
        max_batch_duration_seconds=float(
            data.get("max_batch_duration_seconds", 60.0)
        ),
    )
    loader_kwargs: dict[str, Any] = {
        "batch_size": batch_size,
        "shuffle": train,
        "num_workers": num_workers,
        "pin_memory": True,
        "persistent_workers": num_workers > 0,
        "collate_fn": collate,
        "worker_init_fn": configure_data_worker_threads if num_workers > 0 else None,
        "multiprocessing_context": "spawn" if num_workers > 0 else None,
        "drop_last": train if drop_last is None else bool(drop_last),
    }
    if num_workers > 0:
        loader_kwargs["prefetch_factor"] = max(1, int(os.getenv("CARLA_DATALOADER_PREFETCH", "2")))
    return DataLoader(dataset, **loader_kwargs)


class PairedEmbeddingDataset(Dataset):
    """Pairs precomputed clean/corrupted frozen-encoder embeddings by row.

    Expected torch file:
      {
        "clean": {"fxpp": [N,D], ...},
        "corrupt": {"fxpp": [N,D], ...},
        "metadata": [...]  # optional
      }
    Corruption variants are generated by ``build_corruption_dataset.py`` and
    the cache is built by ``build_embedding_cache.py``; keeping this loader
    independent so it can be reused by the public cache builder.
    """

    def __init__(
        self, path: str, *, return_metadata: bool = False,
        expected_signature: str | None = None,
    ) -> None:
        blob = torch.load(path, map_location="cpu")
        if not isinstance(blob, dict) or "clean" not in blob or "corrupt" not in blob:
            raise ValueError("Paired cache must contain clean and corrupt mappings")
        self.clean = blob["clean"]
        self.corrupt = blob["corrupt"]
        if set(self.clean) != set(self.corrupt):
            raise ValueError("Clean/corrupt embedding branches do not match")
        for name, tensor in self.clean.items():
            validate_embedding_tensor(tensor, f"clean[{name}]")
        for name, tensor in self.corrupt.items():
            validate_embedding_tensor(tensor, f"corrupt[{name}]")
        sizes = {
            tensor.shape[0]
            for tensor in (*self.clean.values(), *self.corrupt.values())
        }
        if len(sizes) != 1:
            raise ValueError("All paired embedding tensors must have equal row counts")
        self.size = sizes.pop()
        metadata = blob.get("metadata", [])
        if metadata is None:
            metadata = []
        if not isinstance(metadata, list):
            raise ValueError("Paired cache metadata must be a list")
        if metadata and len(metadata) != self.size:
            raise ValueError("Paired cache metadata length does not match embeddings")
        self.metadata = metadata
        self.cache_signature = blob.get("cache_signature", {})
        self.signature_sha256 = str(blob.get("signature_sha256", ""))
        if expected_signature is not None and self.signature_sha256 != expected_signature:
            raise ValueError("Paired cache tensor payload/sidecar signature mismatch")
        self.return_metadata = bool(return_metadata)

    def __len__(self) -> int:
        return self.size

    def __getitem__(self, index: int):
        value = {
            "clean": {name: value[index] for name, value in self.clean.items()},
            "corrupt": {name: value[index] for name, value in self.corrupt.items()},
        }
        if self.return_metadata:
            value["metadata"] = self.metadata[index] if self.metadata else {}
        return value


def make_pair_loader(
    path: str,
    batch_size: int,
    num_workers: int,
    train: bool = True,
    *,
    return_metadata: bool = False,
    drop_last: bool | None = None,
    shuffle_seed: int | None = None,
    expected_signature: str | None = None,
):
    generator = None
    if shuffle_seed is not None:
        generator = torch.Generator()
        generator.manual_seed(int(shuffle_seed))
    loader_kwargs: dict[str, Any] = {
        "batch_size": batch_size,
        "shuffle": train,
        "num_workers": num_workers,
        "pin_memory": True,
        "persistent_workers": num_workers > 0,
        "drop_last": train if drop_last is None else bool(drop_last),
        "generator": generator,
        "worker_init_fn": configure_data_worker_threads if num_workers > 0 else None,
    }
    if num_workers > 0:
        loader_kwargs["prefetch_factor"] = max(1, int(os.getenv("CARLA_DATALOADER_PREFETCH", "2")))
    return DataLoader(
        PairedEmbeddingDataset(
            path, return_metadata=return_metadata,
            expected_signature=expected_signature,
        ),
        **loader_kwargs,
    )


class RandAugmentWaveformDataset(Dataset):
    """Load audio and produce one RA view per item.

    Generic offline callers may intentionally use full-song corruption.
    Public RandAugment callers set apply_to_model_window=True, so the native
    window is selected before corruption and branch conversion follows it.
    """

    def __init__(
        self,
        csv_path: str,
        augment: AudioRandAugment,
        *,
        target_sample_rate: int = 44100,
        target_seconds: float = 0.0,
        seed: int = 42,
        require_real: bool = True,
        max_items: int | None = None,
        auto_convert_mp3: bool = True,
        audio_cache_dir: str | None = None,
        crop_mode: str = "random",
        normalize_clean: bool = True,
        noise_paths: Iterable[str] = (),
        rir_paths: Iterable[str] = (),
        static_resources: Mapping[str, Any] | None = None,
        apply_to_model_window: bool = False,
    ) -> None:
        self.rows = self._read_rows(csv_path)
        if max_items is not None:
            self.rows = self.rows[: int(max_items)]
        if require_real and any(int(row["label"]) != 0 for row in self.rows):
            raise ValueError("RandAugment canonicalizer training expects real-only rows")
        self.augment = augment
        self.target_sample_rate = int(target_sample_rate)
        self.target_length = 0 if float(target_seconds) <= 0 else round(float(target_seconds) * self.target_sample_rate)
        self.seed = int(seed)
        self.auto_convert_mp3 = bool(auto_convert_mp3)
        self.audio_cache_dir = audio_cache_dir
        self.crop_mode = str(crop_mode).lower()
        self.normalize_clean = bool(normalize_clean)
        self.noise_paths = tuple(sorted(map(str, noise_paths)))
        self.rir_paths = tuple(sorted(map(str, rir_paths)))
        self.static_resources = dict(static_resources or {})
        self.apply_to_model_window = bool(apply_to_model_window)
        self.epoch = 0
        if self.crop_mode not in {"random", "start", "center"}:
            raise ValueError("crop_mode must be random, start, or center")

    @staticmethod
    def _read_rows(csv_path: str) -> list[dict[str, Any]]:
        with Path(csv_path).open("r", encoding="utf-8", newline="") as handle:
            reader = csv.DictReader(handle)
            if not reader.fieldnames:
                raise ValueError("RandAugment CSV has no header")
            path_key = "full_path" if "full_path" in reader.fieldnames else "path"
            if path_key not in reader.fieldnames or "label" not in reader.fieldnames:
                raise ValueError("RandAugment CSV must contain full_path/path and label")
            return [
                {
                    "full_path": row[path_key],
                    "label": int(row["label"]),
                    "source": row.get("source", ""),
                    "track_id": row.get("track_id", ""),
                }
                for row in reader
            ]

    def __len__(self) -> int:
        return len(self.rows)

    def set_epoch(self, epoch: int) -> None:
        """Change the deterministic online augmentation view for a new epoch."""

        self.epoch = int(epoch)

    def _item_seed(self, index: int) -> int:
        digest = hashlib.sha256(
            f"{self.seed}::{self.epoch}::{index}::{self.rows[index]['full_path']}".encode("utf-8")
        ).digest()
        return int.from_bytes(digest[:8], "big", signed=False)

    def _resource(self, paths: tuple[str, ...], seed: int) -> tuple[torch.Tensor, int, str]:
        if not paths:
            raise ValueError("No resource paths are configured")
        path = paths[int(seed) % len(paths)]
        value, sample_rate = load_audio_cached(
            path, target_sr=None, mono=False, normalize=False, strict=True,
            auto_convert_mp3=False,
        )
        return ensure_stereo(value), int(sample_rate), path

    def __getitem__(self, index: int) -> dict[str, Any]:
        row = self.rows[index]
        clean, sample_rate = load_audio_cached(
            row["full_path"],
            target_sr=None,
            mono=False,
            normalize=False,
            strict=True,
            auto_convert_mp3=self.auto_convert_mp3,
            cache_dir=self.audio_cache_dir,
        )
        clean = ensure_stereo(clean)
        if int(sample_rate) != self.target_sample_rate:
            clean = torchaudio.functional.resample(
                clean, int(sample_rate), self.target_sample_rate
            )
            sample_rate = self.target_sample_rate
        # Match the SOFIA/CARLA base preprocessing path exactly.
        if self.normalize_clean:
            clean = clean / clean.abs().amax().clamp_min(1e-9)
        item_seed = self._item_seed(index)
        if self.apply_to_model_window and self.target_length > 0:
            clean, _ = _crop_or_pad_pair(
                clean, clean, self.target_length, item_seed, self.crop_mode
            )
        resources: dict[str, Any] = dict(self.static_resources)
        resource_paths: dict[str, str] = {}
        if self.noise_paths:
            noise_seed = item_seed
            def load_noise():
                noise, noise_sr, noise_path = self._resource(self.noise_paths, noise_seed)
                resource_paths["noise"] = noise_path
                return (torchaudio.functional.resample(noise, noise_sr, int(sample_rate))
                        if noise_sr != int(sample_rate) else noise)
            resources["noise"] = load_noise
        if self.rir_paths:
            rir_seed = item_seed ^ 0x5A17
            def load_rir():
                rir, rir_sr, rir_path = self._resource(self.rir_paths, rir_seed)
                resource_paths["rir"] = rir_path
                return (torchaudio.functional.resample(rir, rir_sr, int(sample_rate))
                        if rir_sr != int(sample_rate) else rir)
            resources["rir"] = load_rir
        corrupt, operations = self.augment(
            clean,
            int(sample_rate),
            seed=item_seed,
            resources=resources,
            trace_context={
                "track_id": row.get("track_id", ""),
                "epoch": self.epoch,
                "seed": item_seed,
            },
        )
        return {
            "clean": clean,
            "corrupt": ensure_stereo(corrupt),
            "label": torch.tensor(int(row["label"]), dtype=torch.long),
            "sample_rate": int(sample_rate),
            "target_length": self.target_length,
            "metadata": {
                "track_id": row.get("track_id", ""),
                "full_path": row["full_path"],
                "seed": item_seed,
                "epoch": self.epoch,
                "crop_mode": self.crop_mode,
                "operations": operations,
                "resource_paths": resource_paths,
                "augmentation_scope": (
                    "model_window" if self.apply_to_model_window else "full_song"
                ),
            },
        }


def _crop_or_pad_pair(
    clean: torch.Tensor,
    corrupt: torch.Tensor,
    target_length: int,
    seed: int,
    crop_mode: str = "random",
) -> tuple[torch.Tensor, torch.Tensor]:
    max_length = max(clean.shape[-1], corrupt.shape[-1])
    if clean.shape[-1] != corrupt.shape[-1]:
        # Time edits can change duration.  Use the shorter common source span
        # for an embedding pair; the operation remains full-song in the
        # offline benchmark.
        max_length = min(clean.shape[-1], corrupt.shape[-1])
        clean = clean[..., :max_length]
        corrupt = corrupt[..., :max_length]
    if target_length <= 0:
        return clean, corrupt
    if max_length > target_length:
        if crop_mode == "start":
            start = 0
        elif crop_mode == "center":
            start = max((max_length - target_length) // 2, 0)
        else:
            start = random.Random(int(seed)).randint(0, max_length - target_length)
        return (
            clean[..., start : start + target_length],
            corrupt[..., start : start + target_length],
        )
    pad = target_length - max_length
    left = pad // 2
    right = pad - left
    padding = (left, right)
    return F.pad(clean, padding), F.pad(corrupt, padding)


def collate_randaug_pairs(batch: list[dict[str, Any]]) -> dict[str, Any]:
    if not batch:
        raise ValueError("Cannot collate an empty RandAugment batch")
    target_length = int(batch[0]["target_length"])
    clean_items = []
    corrupt_items = []
    metadata = []
    for item in batch:
        clean, corrupt = _crop_or_pad_pair(
            item["clean"],
            item["corrupt"],
            target_length,
            int(item["metadata"]["seed"]),
            str(item["metadata"].get("crop_mode", "random")),
        )
        clean_items.append(clean)
        corrupt_items.append(corrupt)
        metadata.append(item["metadata"])
    try:
        clean_waveforms = torch.stack(clean_items)
        corrupt_waveforms = torch.stack(corrupt_items)
    except RuntimeError as exc:
        raise ValueError(
            "Full-song RandAugment batches require equal durations; use "
            "batch_size=1 or set robustness.randaugment.segment_seconds > 0."
        ) from exc
    return {
        "clean_waveform": clean_waveforms,
        "corrupt_waveform": corrupt_waveforms,
        "label": torch.stack([item["label"] for item in batch]),
        "metadata": metadata,
        "sample_rate": int(batch[0]["sample_rate"]),
    }


def make_randaug_loader(
    csv_path: str,
    augment: AudioRandAugment,
    *,
    target_sample_rate: int,
    target_seconds: float,
    seed: int,
    batch_size: int,
    num_workers: int,
    train: bool = True,
    require_real: bool = True,
    auto_convert_mp3: bool = True,
    audio_cache_dir: str | None = None,
    crop_mode: str = "random",
    normalize_clean: bool = True,
    noise_paths: Iterable[str] = (),
    rir_paths: Iterable[str] = (),
    static_resources: Mapping[str, Any] | None = None,
    apply_to_model_window: bool = False,
) -> DataLoader:
    dataset = RandAugmentWaveformDataset(
        csv_path,
        augment,
        target_sample_rate=target_sample_rate,
        target_seconds=target_seconds,
        seed=seed,
        require_real=require_real,
        auto_convert_mp3=auto_convert_mp3,
        audio_cache_dir=audio_cache_dir,
        crop_mode=crop_mode,
        normalize_clean=normalize_clean,
        noise_paths=noise_paths,
        rir_paths=rir_paths,
        static_resources=static_resources,
        apply_to_model_window=apply_to_model_window,
    )
    loader_kwargs: dict[str, Any] = {
        "batch_size": batch_size,
        "shuffle": train,
        "num_workers": num_workers,
        "pin_memory": True,
        "persistent_workers": num_workers > 0,
        "drop_last": train,
        "collate_fn": collate_randaug_pairs,
        "worker_init_fn": configure_data_worker_threads if num_workers > 0 else None,
        "multiprocessing_context": "spawn" if num_workers > 0 else None,
    }
    if num_workers > 0:
        loader_kwargs["prefetch_factor"] = max(1, int(os.getenv("CARLA_DATALOADER_PREFETCH", "2")))
    return DataLoader(dataset, **loader_kwargs)
